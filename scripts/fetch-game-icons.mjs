// Waxlight iconography pipeline (see .claude/skills/waxlight-iconography):
// fetches curated CC BY 3.0 icons from the game-icons.net repository, strips
// the background plate, and generates src/components/atlas/gameIcons.tsx with
// the raw glyph paths so components can render them in palette colors.
// Usage: node scripts/fetch-game-icons.mjs
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

// Chosen after a wide visual search across game-icons.net authors (see
// docs/ICON_RESEARCH.md for the montage/rationale): each icon was picked by
// rendering it as an actual in-game medallion token, not by its raw preview.
const ICONS = {
  cowled: "lorc/cowled",
  "skull-crack": "lorc/skull-crack",
  "ringing-bell": "lorc/ringing-bell",
  "monster-grasp": "lorc/monster-grasp",
  ribcage: "lorc/ribcage",
  "crowned-skull": "lorc/crowned-skull"
};

const outDir = resolve("src/assets/icons/game-icons");
mkdirSync(outDir, { recursive: true });

const entries = [];
const attribution = [];
for (const [key, path] of Object.entries(ICONS)) {
  const url = `https://raw.githubusercontent.com/game-icons/icons/master/${path}.svg`;
  const response = await fetch(url);
  if (!response.ok) {
    console.error(`[icons] MISSING ${path} (${response.status})`);
    continue;
  }
  const svg = await response.text();
  writeFileSync(resolve(outDir, `${key}.svg`), svg);
  const paths = [...svg.matchAll(/<path\b[^>]*\bd="([^"]+)"/g)]
    .map((match) => match[1])
    .filter((d) => !/^M0 0h512v512H0z$/i.test(d.trim()));
  entries.push(`  "${key}": ${JSON.stringify(paths)}`);
  attribution.push(`- ${key}: "${path}" by ${path.split("/")[0]}`);
  console.log(`[icons] ${key} <- ${path} (${paths.length} path${paths.length === 1 ? "" : "s"})`);
}

const tsx = `import type { SVGProps } from "react";

// GENERATED by scripts/fetch-game-icons.mjs — do not edit by hand.
// Glyphs from game-icons.net (CC BY 3.0); see src/assets/icons/ATTRIBUTION.md.

export const GAME_ICON_PATHS: Record<string, string[]> = {
${entries.join(",\n")}
};

export function GameIcon({ icon, color, ...props }: { icon: string; color: string } & SVGProps<SVGSVGElement>) {
  const paths = GAME_ICON_PATHS[icon];
  if (!paths) {
    return null;
  }
  return (
    <svg viewBox="0 0 512 512" {...props} aria-hidden="true">
      {paths.map((d, index) => (
        <path d={d} fill={color} key={index} />
      ))}
    </svg>
  );
}
`;
writeFileSync(resolve("src/components/atlas/gameIcons.tsx"), tsx);

writeFileSync(
  resolve("src/assets/icons/ATTRIBUTION.md"),
  `# Icon Attribution

Creature/system glyphs in \`game-icons/\` are from [game-icons.net](https://game-icons.net),
licensed [CC BY 3.0](https://creativecommons.org/licenses/by/3.0/). Authors: Lorc, Delapouite.

${attribution.join("\n")}

Fetched by \`scripts/fetch-game-icons.mjs\`; recolored at render time into the
Waxlight palette (docs/UI_UX_GOALS.md).
`
);
console.log("[icons] generated gameIcons.tsx + ATTRIBUTION.md");
